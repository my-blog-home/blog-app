/**
 * 정책 문서에 들어가는 운영 정보. 서비스를 공개하기 전에 실제 값으로 바꿔야 한다.
 * 정책 본문의 {{운영자}}, {{연락처}}, {{시행일}}, {{보호책임자}} 자리에 들어간다.
 */
export const LEGAL = {
  운영자: '[운영자 이름]',
  연락처: '[문의 이메일]',
  보호책임자: '[개인정보 보호책임자 이름]',
  시행일: '[시행일, 예: 2026년 10월 20일]',
  // 개인정보를 맡기는 곳(서버·DB 호스팅, 메일 발송). 실제 이용하는 곳으로 바꾼다
  위탁: '[서버·데이터베이스 호스팅 업체], [메일 발송 서비스(사용하는 경우)]',
}

export function fillPlaceholders(text: string): string {
  return text.replace(/\{\{(운영자|연락처|보호책임자|시행일|위탁)\}\}/g, (_, key: keyof typeof LEGAL) =>
    // 대괄호가 마크다운 링크로 읽히지 않게 이스케이프한다
    LEGAL[key].replace(/[[\]]/g, '\\$&'),
  )
}
