-- 실시간 인기 검색어용 검색 기록 (FR-073, BR-29). 대소문자만 다른 검색어는 keyword_key(소문자)로 합친다.
-- 이틀이 지난 기록은 매일 지운다
CREATE TABLE search_log (
    id           BIGSERIAL PRIMARY KEY,
    keyword      VARCHAR(50) NOT NULL,
    keyword_key  VARCHAR(50) NOT NULL,
    searched_at  TIMESTAMPTZ NOT NULL
);
CREATE INDEX ix_search_log_time ON search_log (searched_at);
CREATE INDEX ix_search_log_key ON search_log (keyword_key, searched_at);

-- 공지·이용 안내 (FR-077, BR-30). 종류는 공지(NOTICE)와 이용법(GUIDE).
-- created_by는 쓴 관리자 자리다. 관리자 기능이 생기기 전 처음 넣는 안내는 비워 둔다.
-- 회원 표에 외래 키를 걸지 않는다: 회원이 지워져도(테스트의 회원 표 비우기 포함) 안내는 남아야 하기 때문이다
CREATE TABLE notice (
    id          BIGSERIAL PRIMARY KEY,
    created_by  BIGINT,
    type        VARCHAR(10)  NOT NULL CHECK (type IN ('NOTICE', 'GUIDE')),
    title       VARCHAR(100) NOT NULL,
    content     TEXT         NOT NULL,
    pinned      BOOLEAN      NOT NULL DEFAULT false,
    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ
);
CREATE INDEX ix_notice_list ON notice (pinned DESC, created_at DESC, id DESC);

